// Build-time only: no image processing, font requests or extra dependencies in the Worker.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import sharp from "sharp";
import { brand } from "../src/lib/branding/config.ts";

const directory = new URL("../public/branding/", import.meta.url);
await mkdir(directory, { recursive: true });
const c = brand.colors;
const escape = (s) => s.replace(/[<>&"]/g, (v) => ({ "<": "&lt;", ">": "&gt;", "&": "&amp;", '"': "&quot;" })[v]);
// Vector interpretation of the supplied geometric ribbon. Replace with the approved master when available.
const paths = `<defs><linearGradient id="blue" x2="1" y2="1"><stop stop-color="${c.cyan}"/><stop offset="1" stop-color="${c.blue}"/></linearGradient><linearGradient id="purple" x2="1" y2="1"><stop stop-color="${c.purple}"/><stop offset="1" stop-color="${c.violet}"/></linearGradient></defs><path d="M16 39 64 11 112 39 64 67 38 52 38 111 16 98Z" fill="url(#blue)"/><path d="m64 11 48 28-22 13-26-15-48 28V39Z" fill="url(#blue)"/><path d="m112 39-48 28v57l23-14V81l25-15Z" fill="url(#purple)"/><path d="m64 67 48-28v27L64 94Z" fill="url(#purple)"/>`;
const svg = (body, viewBox = "0 0 128 136") => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}">${body}</svg>`;
const mark = svg(paths);
await writeFile(new URL("mark.svg", directory), mark);
for (const [mode, color] of [["light", c.graphite], ["dark", "#F8FAFC"]]) {
	await writeFile(new URL(`logo-${mode}.svg`, directory), svg(`${paths}<text x="148" y="83" fill="${color}" font-family="Inter,Arial,sans-serif" font-weight="700" font-size="64" letter-spacing="-2">${escape(brand.appName)}</text>`, "0 0 560 136"));
}
for (const size of [48, 96, 192, 512]) {
	await sharp(Buffer.from(mark)).resize(size, size, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } }).png().toFile(new URL(`../icon-${size}.png`, directory).pathname);
}
await sharp(Buffer.from(mark)).resize(180, 180, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } }).png().toFile(new URL("../apple-touch-icon.png", directory).pathname);
await sharp(Buffer.from(svg(`<rect width="128" height="136" fill="${c.graphite}"/><g transform="translate(19.2 20.4) scale(.7)">${paths}</g>`))).resize(512, 512, { fit: "fill" }).png().toFile(new URL("../icon-maskable-512.png", directory).pathname);
const png = await sharp(Buffer.from(mark)).resize(32, 32, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } }).png().toBuffer();
const ico = Buffer.alloc(22); ico.writeUInt16LE(1, 2); ico.writeUInt16LE(1, 4); ico[6] = 32; ico[7] = 32; ico.writeUInt16LE(1, 10); ico.writeUInt16LE(32, 12); ico.writeUInt32LE(png.length, 14); ico.writeUInt32LE(22, 18);
await writeFile(new URL("../favicon.ico", directory), Buffer.concat([ico, png]));

const neutrals = { 50: c.background, 100: "#F1F5F9", 200: c.border, 300: "#CBD5E1", 400: "#64748B", 500: "#64748B", 600: c.gray, 700: "#334155", 800: c.slate, 900: c.graphite, 950: "#020617" };
const darkNeutrals = { 50: c.slate, 100: "#243247", 200: "#334155", 300: c.gray, 400: "#94A3B8", 500: "#A8B5C8", 600: "#CBD5E1", 700: c.border, 800: "#F1F5F9", 900: c.background, 950: "#FFFFFF" };
const palette = (values) => ["neutral", "gray", "slate", "zinc", "stone"].flatMap((name) => Object.entries(values).map(([n, value]) => `\t--color-${name}-${n}: ${value};`)).join("\n");
const tokens = `/* Generated by npm run brand:prepare from src/lib/branding/config.ts. */
:root {
	--brand-blue: ${c.blue}; --brand-purple: ${c.purple}; --brand-cyan: ${c.cyan}; --brand-violet: ${c.violet};
	--background: ${c.background}; --foreground: ${c.graphite}; --card: #FFFFFF; --muted: #F1F5F9; --border: ${c.border};
	--primary: ${c.blue}; --primary-hover: #1D4ED8; --primary-foreground: #FFFFFF;
	--success: ${c.success}; --warning: ${c.warning}; --danger: ${c.danger};
	--radius-control: .75rem; --radius-panel: 1.5rem; --space-unit: .25rem;
	--shadow-panel: 0 12px 40px -20px #0B122026;
	--color-blue-50: #EFF6FF; --color-blue-100: #DBEAFE; --color-blue-200: #BFDBFE; --color-blue-300: #93C5FD; --color-blue-400: #60A5FA; --color-blue-500: #3B82F6; --color-blue-600: ${c.blue}; --color-blue-700: #1D4ED8; --color-blue-800: #1E40AF; --color-blue-900: #1E3A8A; --color-blue-950: #172554;
${palette(neutrals)}
}
.dark {
	--background: ${c.graphite}; --foreground: ${c.background}; --card: #131E30; --muted: ${c.slate}; --border: #334155;
	--primary: #93C5FD; --primary-hover: #BFDBFE; --primary-foreground: ${c.graphite};
	--color-white: #131E30; --shadow-panel: 0 12px 40px -20px #00000066;
	--color-blue-50: #172B4A; --color-blue-100: #1E365B; --color-blue-200: #244679; --color-blue-300: #2757A0; --color-blue-400: #3B82F6; --color-blue-500: #60A5FA; --color-blue-600: #93C5FD; --color-blue-700: #BFDBFE; --color-blue-800: #DBEAFE; --color-blue-900: #EFF6FF; --color-blue-950: #F8FAFC;
${palette(darkNeutrals)}
}
`;
await writeFile(new URL("../src/app/brand-tokens.css", import.meta.url), tokens);
// Offline/PWA files cannot import the TS configuration at runtime.
const offlineFile = new URL("../public/offline.html", import.meta.url);
let offline = await readFile(offlineFile, "utf8");
offline = offline.replace(/<title>.*?<\/title>/, `<title>Sem conexão · ${escape(brand.appName)}</title>`).replace(/<p>.*?<\/p>/, `<p>Não foi possível conectar ao ${escape(brand.appName)}. Verifique sua conexão e tente novamente.</p>`);
offline = offline.replace(/<svg\b[\s\S]*?<\/svg>/, mark);
await writeFile(offlineFile, offline);
const swFile = new URL("../public/sw.js", import.meta.url);
const sw = await readFile(swFile, "utf8");
await writeFile(swFile, sw.replace(/(const DEFAULT_NOTIFICATION = \{\s*title: )"[^"]*"/, (_, prefix) => prefix + JSON.stringify(brand.appName)));
console.log("OwnForge: generated tokens, SVG logos, PWA icons and favicon.");
